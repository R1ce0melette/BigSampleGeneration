#!/usr/bin/env python3
import os
import sys
import json
"""
Helper script that reads the code generated by the LLMs and creates a dataset in jsonl format
Usage: python make_dataset.py <path-to-directory> <model>
"""
def extract_comments_and_code(filepath):
	comments = []
	code_lines = []
	found_delimiter = False
	with open(filepath, 'r', encoding='utf-8') as f:
		for line in f:
			if not found_delimiter:
				if 'pragma solidity' in line or 'SPDX-License' in line:
					found_delimiter = True
					code_lines.append(line) 
				elif line.strip().startswith('//'):
					comments.append(line.lstrip('//').rstrip('\n'))
				elif line.strip() == '':
					comments.append(line.rstrip('\n'))
				else:
					found_delimiter = True
					code_lines.append(line)
			else:
				code_lines.append(line)
	return comments, code_lines

def main():
	if len(sys.argv) != 3:
		print(f"Usage: make_dataset.py <path-to-directory> <model>")
		sys.exit(1)
	dir_path = sys.argv[1]
	model = sys.argv[2]
	output_path = os.path.join(dir_path, 'dataset.jsonl')
	with open(output_path, 'w', encoding='utf-8') as out_f:
		for fname in os.listdir(dir_path):
			if fname.endswith('.sol'):
				fpath = os.path.join(dir_path, fname)
				comments, code_lines = extract_comments_and_code(fpath)
				input_prompt = '\n'.join([c for c in comments if c.strip() != ''])
				output_code = ''.join(code_lines).lstrip('\n')
				data = {
					'input_prompt': input_prompt,
					'output_code': output_code,
					'model': model
				}
				out_f.write(json.dumps(data, ensure_ascii=False) + '\n')

if __name__ == '__main__':
	main()
